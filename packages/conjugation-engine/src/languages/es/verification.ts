/**
 * What was read to check each lexicon lemma: a record kept by hand, one line per lemma, never computed. The authority for
 * a lemma is its DLE entry with the conjugation table (`dle`); `raeRead` says whether that page was read. On 24 and 27 Nov
 * 2026 dle.rae.es and www.rae.es answered HTTP 403 to automated reading and no browser was available to open them by
 * hand, so no lemma has been checked against the RAE: every entry is unverified until someone opens its `dle` page.
 * `secondary` lists the other pages that were actually read for the lemma (the English Wiktionary conjugation table,
 * read through a look-up helper in stint 1 or by the implementer); a secondary page does not verify an entry.
 * `tests/es/verification.test.ts` checks that every lemma of the lexicon has exactly one line here.
 */

type Url = `https://${string}`;

export interface PageRead {
  readonly url: Url;
  /** The day the page was read. */
  readonly read: string;
  readonly by: 'implementer' | 'look-up helper';
  readonly note?: string;
}

export interface LemmaVerification {
  /** The lemma's DLE entry, the page that would verify it. */
  readonly dle: Url;
  /** Whether that page (or another RAE page for the lemma) was read. */
  readonly raeRead: boolean;
  readonly secondary: readonly PageRead[];
}

const wikt = (lemma: string, read: string, by: PageRead['by']): PageRead => ({ url: `https://en.wiktionary.org/wiki/${lemma}`, read, by });

